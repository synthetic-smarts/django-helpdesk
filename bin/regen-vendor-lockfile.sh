#!/usr/bin/env bash
# Regenerate package-lock.json for the frontend vendor build and PROVE that a
# frozen `npm ci` from it reproduces byte-identical npm-built vendored assets to
# the re-resolving `npm install` the synsmarts-api image build uses.
#
# Runs entirely in a THROWAWAY clone (never mutates your live checkout — the fork
# commits some non-npm vendor assets, e.g. flot, that npm doesn't manage, and a
# naive `rm -rf vendor/*` would delete them). Copies the verified lockfile back.
#
# MUST run in the SAME toolchain the synsmarts-api Dockerfile uses: Debian bookworm
# + apt nodejs/npm (node 18). A lockfile generated by a newer npm can resolve
# differently and break `npm ci` in the node-18 image build
# (Test-Environment-Version-Parity). Example (from the fork repo root):
#   docker run --rm -v "$PWD":/w -w /w -e HOME=/tmp python:3.12-slim-bookworm bash -c '
#     apt-get update >/dev/null && apt-get install -y --no-install-recommends git make nodejs npm >/dev/null &&
#     git config --global --add safe.directory /w && bin/regen-vendor-lockfile.sh'
#
# Produces: package-lock.json in the repo root (commit it). Exits non-zero if
# npm ci does NOT reproduce the npm-install vendored output.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "node $(node --version)  npm $(npm --version)"
git -C "$ROOT" clone --quiet "$ROOT" "$WORK/repo"
cd "$WORK/repo"

# Only the npm-managed vendor subdirs (build:static's VENDORS) are compared;
# committed non-npm assets (flot, flot-tooltip, README) are irrelevant here.
VENDOR_DIR="src/helpdesk/static/helpdesk/vendor"
hash_npm_vendors() {
  # Hash only subdirs that build:static rebuilt this run (its stdout names them),
  # so committed non-npm vendor files never enter the comparison.
  sort -u "$WORK/built.list" | while read -r v; do
    [ -d "$VENDOR_DIR/$v" ] && find "$VENDOR_DIR/$v" -type f -exec sha256sum {} +
  done | sed "s#$WORK/repo/##" | sort -k2
}

echo "=== 1. npm install (re-resolve package.json, as the image build does today) ==="
npm install --no-audit --no-fund
npm run build:static 2>&1 | tee "$WORK/build1.log"
grep -oE "Processing vendor: [^ ]+" "$WORK/build1.log" | awk '{print $3}' > "$WORK/built.list"
# Guard against a false pass: if build:static named no vendors, both hashes would be
# empty and the diff would trivially match. Require a non-empty list that includes the
# load-bearing bootstrap vendor (the Dockerfile's post-build sentinel is bootstrap too).
test -s "$WORK/built.list" || { echo "no vendors built by build:static — aborting" >&2; exit 1; }
grep -qx bootstrap "$WORK/built.list" || { echo "bootstrap missing from built vendors — aborting" >&2; exit 1; }
hash_npm_vendors > "$WORK/vendor-install.sha"
cp package-lock.json "$WORK/lock.gen"

echo "=== 2. wipe node_modules + the npm vendor subdirs, npm ci from the lock, rebuild ==="
rm -rf node_modules
while read -r v; do rm -rf "$VENDOR_DIR/$v"; done < "$WORK/built.list"
npm ci --no-audit --no-fund
npm run build:static >/dev/null
hash_npm_vendors > "$WORK/vendor-ci.sha"

echo "=== 3. compare: npm ci output MUST equal npm install output ==="
if diff -u "$WORK/vendor-install.sha" "$WORK/vendor-ci.sha"; then
  cp "$WORK/lock.gen" "$ROOT/package-lock.json"
  echo "OK: npm ci reproduces byte-identical npm vendored assets to npm install."
  echo "Wrote $ROOT/package-lock.json — the Dockerfile can switch npm install -> npm ci."
else
  echo "MISMATCH: npm ci output differs from npm install — do NOT switch to npm ci." >&2
  exit 1
fi
